/**
 * Pure Engine Function: Rotates the vehicle list strictly according to quarry rules:
 * - Position 1: RZ MINING is FIXED and NEVER rotates.
 * - Positions 2 onward: Rotates by shifting eligible outside/company vehicles forward by 1.
 * - Changing a rotation creates a new snapshot without modifying historical records.
 */
export function generateNextRotationEngine(
  currentRotation: DailyRotation,
  newDate: string,
  newCycleNumber?: number
): DailyRotation {
  if (!currentRotation || !currentRotation.entries || currentRotation.entries.length === 0) {
    throw new Error('Cannot advance rotation from empty entries');
  }

  // 1. Identify Fixed Position 1: RZ MINING (MUST NEVER ROTATE)
  const fixedPosition1 = currentRotation.entries.find((e) => e.isFixed) || currentRotation.entries[0];
  
  // 2. Identify Rotating Positions (Positions 2 onward)
  const rotatingVehicles = currentRotation.entries.filter((e) => !e.isFixed);

  // 3. Shift rotating vehicles: Position 2 shifts to end; Position 3 becomes Position 2, etc.
  let shiftedVehicles: DailyRotationEntry[] = [];
  if (rotatingVehicles.length > 1) {
    shiftedVehicles = [...rotatingVehicles.slice(1), rotatingVehicles[0]];
  } else {
    shiftedVehicles = [...rotatingVehicles];
  }

  // 4. Construct new entries with updated positions:
  // Position 1: RZ MINING — FIXED
  // Position 2..N: shifted vehicles
  const newEntries: DailyRotationEntry[] = [
    {
      ...fixedPosition1,
      position: 1,
      isFixed: true,
      status: 'Waiting',
      entryTime: '06:30 AM',
      remarks: 'RZ MINING — FIXED (Never Rotates)',
    },
    ...shiftedVehicles.map((v, idx) => ({
      ...v,
      position: idx + 2,
      isFixed: false,
      status: 'Waiting' as const,
      entryTime: `0${7 + Math.floor(idx / 3)}:${((idx + 1) * 15) % 60 < 10 ? '0' : ''}${((idx + 1) * 15) % 60} AM`,
      remarks: idx === 0 ? 'Next Turn Leader' : `Turn #${idx + 1}`,
    })),
  ];

  const cycleNum = newCycleNumber !== undefined ? newCycleNumber : (currentRotation.rotationNumber || 1) + 1;

  return {
    id: `rot-${newDate}-c${cycleNum}-${Date.now().toString().slice(-4)}`,
    rotationDate: newDate,
    rotationNumber: cycleNum,
    status: 'Active',
    notes: `Rotation Cycle #${cycleNum} advanced. Position 1 fixed to RZ MINING.`,
    entries: newEntries,
    createdAt: new Date().toISOString(),
    created_by_name: 'Nafid',
    created_by_email: 'nafidkhan@racezoneventures.com',
  };
}

